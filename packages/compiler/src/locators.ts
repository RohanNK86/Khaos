import type { ElementFingerprint, Locator } from '@mcpify/contracts';

const BUTTON_INPUT = /^(submit|button|reset|image)$/;

/** Ids/names that a framework generated (they change between builds/sessions), e.g. "ember123", "react-x9f3a8c1d". */
export function looksAutoGenerated(id: string): boolean {
  return /\d{5,}/.test(id)
    || /[0-9a-f]{8,}/i.test(id.replace(/[g-z]/gi, '_')) && /\d/.test(id)
    || /^[0-9a-f]{8}-[0-9a-f]{4}-/i.test(id)
    || /^(ember|react-|mui-|ext-gen|ext-comp|yui_|gwt-|ng-|j_id|:r|radix-|headlessui-)/i.test(id);
}

export const isButtonLike = (fp: ElementFingerprint) =>
  fp.tag === 'button' || (fp.tag === 'input' && BUTTON_INPUT.test(fp.type ?? '')) || fp.role === 'button';
export const isLink = (fp: ElementFingerprint) => fp.tag === 'a' || fp.role === 'link';
export const isControl = (fp: ElementFingerprint) =>
  fp.tag === 'select' || fp.tag === 'textarea' || (fp.tag === 'input' && !BUTTON_INPUT.test(fp.type ?? ''));

/** ARIA role the engine's resolver understands for this element. */
export function roleOf(fp: ElementFingerprint): string | undefined {
  if (fp.role) return fp.role;
  if (isButtonLike(fp)) return 'button';
  if (isLink(fp)) return 'link';
  if (fp.tag === 'select') return 'combobox';
  if (fp.tag === 'textarea') return 'textbox';
  if (fp.tag !== 'input') return undefined;
  if (fp.type === 'checkbox' || fp.type === 'radio') return fp.type;
  return /^(text|email|number|tel|date)$/.test(fp.type ?? 'text') ? 'textbox' : undefined;
}

/**
 * Candidate locators for an element, best first:
 * testid > id (not auto-generated) > name > label > role+name > text (buttons/links) > near > css > xpath.
 * Candidates are NOT verified here; see SnapshotDom.verify / pickLocators.
 */
export function candidateLocators(fp: ElementFingerprint, extra: { label?: string } = {}): Locator[] {
  const out: Locator[] = [];
  const label = fp.label ?? extra.label;
  const clickable = isButtonLike(fp) || isLink(fp);
  const text = fp.text ?? fp.ariaLabel;
  if (fp.testid) out.push({ kind: 'testid', value: fp.testid });
  if (fp.id && !looksAutoGenerated(fp.id)) out.push({ kind: 'id', value: fp.id });
  if (fp.name && !looksAutoGenerated(fp.name)) out.push({ kind: 'name', value: fp.name });
  if (isControl(fp) && label) out.push({ kind: 'label', value: label });
  const role = roleOf(fp);
  const accName = clickable ? text : label ?? fp.ariaLabel;
  if (role && accName) out.push({ kind: 'role', role, name: accName });
  if (clickable && text) out.push({ kind: 'text', value: text });
  const anchor = label ?? fp.nearText;
  if (anchor) out.push({ kind: 'near', anchorText: anchor, tag: fp.tag });
  if (fp.cssPath) out.push({ kind: 'css', value: fp.cssPath });
  if (fp.xpath) out.push({ kind: 'xpath', value: fp.xpath });
  return out;
}

/** Keep verified candidates in priority order, 2–5 of them when possible. */
export function pickLocators(candidates: Locator[], verified: boolean[] | null, max = 5): { locators: Locator[]; verified: boolean } {
  if (!verified) return { locators: candidates.slice(0, Math.min(max, 3)), verified: false };
  const ok = candidates.filter((_, i) => verified[i]);
  if (ok.length === 0) return { locators: candidates.slice(0, Math.min(max, 3)), verified: false };
  return { locators: ok.slice(0, max), verified: true };
}
