import { expect, test } from 'vitest';
import type { ElementFingerprint } from '@mcpify/contracts';
import {
  candidateLocators, classifyClick, compile, looksAutoGenerated, paramNameFromLabel, patternFromValue, pickLocators, sensitiveParamName,
} from '../src/index.js';
import { portal1Fixture } from './fixture.js';
import { golden, shape } from './helpers.js';

const fp = (over: Partial<ElementFingerprint>): ElementFingerprint => ({ tag: 'input', type: 'text', classes: [], cssPath: 'input', xpath: '/html[1]/body[1]/input[1]', ...over });

test('auto-generated ids and names are skipped', () => {
  expect(looksAutoGenerated('ctl00_ContentPlaceHolder1_txtApplicantName')).toBe(false);
  expect(looksAutoGenerated('email')).toBe(false);
  for (const id of ['ember1234', 'react-select-3a9f1c2d', ':r1:', 'field_839201', '0d9f6c3e-1a2b-4c3d']) expect(looksAutoGenerated(id), id).toBe(true);
  const locs = candidateLocators(fp({ id: 'ember98765', name: 'city', label: 'City' }));
  expect(locs.map(l => l.kind)).toEqual(['name', 'label', 'role', 'near', 'css', 'xpath']);
});

test('candidate order: testid > id > name > label > role > text > near > css > xpath', () => {
  expect(candidateLocators(fp({ testid: 't', id: 'i', name: 'n', label: 'L' })).map(l => l.kind))
    .toEqual(['testid', 'id', 'name', 'label', 'role', 'near', 'css', 'xpath']);
  const button = candidateLocators(fp({ type: 'submit', id: 'go', text: 'Send OTP' }));
  expect(button.slice(0, 3)).toEqual([{ kind: 'id', value: 'go' }, { kind: 'role', role: 'button', name: 'Send OTP' }, { kind: 'text', value: 'Send OTP' }]);
  expect(pickLocators(button, button.map((_, i) => i !== 1)).locators.map(l => l.kind)).toEqual(['id', 'text', 'css', 'xpath']);
});

test('rules-only param names from labels', () => {
  expect(paramNameFromLabel('Applicant Name')).toBe('applicant_name');
  expect(paramNameFromLabel('Mobile Number')).toBe('mobile');
  expect(paramNameFromLabel('Email ID')).toBe('email');
  expect(paramNameFromLabel('Income Certificate (PDF/JPG, max 1 MB)')).toBe('income_certificate');
  expect(paramNameFromLabel('I declare the above information is true')).toBe('declaration');
  expect(paramNameFromLabel(undefined, ['ctl00$ContentPlaceHolder1$txtFamIncome'])).toBe('fam_income');
  expect(sensitiveParamName(['Type the characters shown', 'ctl00$ContentPlaceHolder1$txtCaptcha'])).toBe('captcha');
  expect(sensitiveParamName(['Enter OTP'])).toBe('otp');
  expect(patternFromValue('SSP-2026-000123')).toBe('SSP-\\d{4}-\\d{6}');
});

test('click risk: Next to the next form page is fill; send/submit and the last button are commit; links read', () => {
  const next = fp({ type: 'submit', text: 'Next', inForm: 'f' });
  const facts = { title: '', headings: [], lines: [], controls: 5 };
  const moved = { url: 'http://x/apply/2', navigated: true };
  expect(classifyClick(next, { fromUrl: 'http://x/apply/1', after: moved, afterFacts: facts, isLastClick: false })).toBe('fill');
  expect(classifyClick(next, { fromUrl: 'http://x/apply/1', after: moved, afterFacts: { ...facts, controls: 0 }, isLastClick: false })).toBe('commit');
  expect(classifyClick(next, { fromUrl: 'http://x/apply/1', after: moved, afterFacts: facts, isLastClick: true })).toBe('commit');
  expect(classifyClick(fp({ type: 'submit', text: 'Send OTP' }), { fromUrl: 'http://x/a', isLastClick: false })).toBe('commit');
  expect(classifyClick(fp({ tag: 'a', type: undefined, text: 'Check status' }), { fromUrl: 'http://x/a', isLastClick: false })).toBe('read');
});

test('saved Portal 1 recording compiles to the golden shape (fixture, no live portal)', async () => {
  process.env.LLM_DISABLED = '1';
  const { recording, loadSnapshot } = await portal1Fixture();
  const draft = await compile(recording, { loadSnapshot, llm: false });
  expect(shape(draft.steps)).toEqual(shape((await golden()).steps));
  expect(draft.warnings).toEqual([]);
  expect(draft.outputs).toEqual(['application_id']);
  expect(draft.steps.find(s => s.id === 'enter_otp')).toMatchObject({ risk: 'auth', repair: 'human', sensitive: true, action: { type: 'userInput', param: 'otp' } });
  expect(JSON.stringify(draft)).not.toContain('•••');
}, 60_000);

test('without snapshots the compiler still produces a draft, with warnings and unverified locators', async () => {
  const { recording } = await portal1Fixture();
  const draft = await compile(recording, { loadSnapshot: async () => null, llm: false });
  expect(draft.steps.length).toBeGreaterThan(15);
  expect(draft.warnings.some(w => /could not be verified/.test(w))).toBe(true);
}, 60_000);
